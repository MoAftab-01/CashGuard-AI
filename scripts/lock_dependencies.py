"""Pin installed dependency closures, evaluating Windows/Linux/macOS markers.

Uses installed distribution metadata; it does not download or resolve new versions.
An absent dependency for any target is an error rather than an invented pin.
"""

from importlib.metadata import distribution
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
PLATFORMS = {"Windows": ("win32", "nt"), "Linux": ("linux", "posix"), "Darwin": ("darwin", "posix")}
RUNTIME = ("pandas", "numpy", "pydantic", "scikit-learn", "streamlit", "plotly", "requests", "fastapi", "uvicorn", "prometheus-client")


def lock(roots):
    needed, seen = {}, set()
    for platform, (sys_platform, os_name) in PLATFORMS.items():
        environment = {**default_environment(), "platform_system": platform,
                       "sys_platform": sys_platform, "os_name": os_name}
        pending = [(root, frozenset()) for root in roots]
        while pending:
            name, extras = pending.pop()
            name = canonicalize_name(name)
            identity = (platform, name, extras)
            if identity in seen:
                continue
            seen.add(identity)
            installed = distribution(name)
            needed.setdefault(name, set()).add(platform)
            for requirement in installed.requires or ():
                parsed = Requirement(requirement)
                if parsed.marker is None or any(parsed.marker.evaluate({**environment, "extra": extra}) for extra in extras or ("",)):
                    pending.append((parsed.name, frozenset(parsed.extras)))
    lines = ["# Python 3.12; exact installed versions, platform markers from package metadata.",
             "# Generated by python -m scripts.lock_dependencies; no credentials or private data."]
    for name, platforms in sorted(needed.items()):
        line = f"{name}=={distribution(name).version}"
        if platforms != set(PLATFORMS):
            line += "; " + " or ".join(f'platform_system == "{platform}"' for platform in sorted(platforms))
        lines.append(line)
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    for filename, roots in (("requirements-runtime.lock.txt", RUNTIME),
                            ("requirements-mlops.lock.txt", (*RUNTIME, "mlflow")),
                            ("requirements.lock.txt", (*RUNTIME, "mlflow", "pytest", "httpx", "ruff", "pyyaml"))):
        text = lock(roots)
        (ROOT / filename).write_text(text, encoding="utf-8")
        print(f"Pinned {len(text.splitlines()) - 2} packages: {filename}")
